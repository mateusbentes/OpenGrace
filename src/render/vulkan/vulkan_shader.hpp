#pragma once

#include <cstdint>
#include <map>
#include <string>
#include <vector>

#include "grace/render/shader.hpp"
#include "vk_loader.hpp"

#include "vulkan_shader_library.hpp"

namespace grace::render::vulkan {

/// One Vulkan shader program: the SPIR-V modules for its two stages plus the
/// staging CPU-side uniform buffer the setUniform calls write into.
///
/// The backend compiles the GLSL 450 core sources in vulkan_shader_library.hpp
/// to SPIR-V at build time (glslangValidator); this class holds the resulting
/// bytes and the std140 layout table for its uniform block. setUniform writes
/// through the layout table's name lookup into the staging buffer; the backend
/// uploads the buffer before a draw that uses the program (decision 14: the
/// engine sets uniforms by name, the API-neutral contract never changes).
class VkShaderProgram final : public ShaderProgram
{
public:
    /// Compiles the library sources for `id` and prepares the std140
    /// staging buffer. Throws std::runtime_error when the id has no
    /// library entry.
    explicit VkShaderProgram(ShaderProgramId id);
    ~VkShaderProgram() override = default;

    VkShaderProgram(const VkShaderProgram&) = delete;
    VkShaderProgram& operator=(const VkShaderProgram&) = delete;

    void use() override;
    void setUniform(const char* name, float value) override;
    void setUniform(const char* name, int value) override;
    void setUniform(const char* name, const core::vec2& value) override;
    void setUniform(const char* name, const core::vec3& value) override;
    void setUniform(const char* name, const core::vec4& value) override;
    void setUniform(const char* name, const core::mat4& value) override;
    void setUniformSampler(const char* name,
                           std::int32_t textureUnit) override;
    std::int32_t uniformLocation(const char* name) override;

    /// The compiled SPIR-V of the program's stages (the arrays generated by
    /// the build step). The empty array means the program is the deliberately
    /// broken pair (the library still declares it; the compilation is
    /// expected to fail).
    const std::uint32_t* vertexSpirv() const noexcept
    {
        return m_vertex_spirv;
    }
    const std::uint32_t* fragmentSpirv() const noexcept
    {
        return m_fragment_spirv;
    }
    std::uint32_t vertexSpirvWords() const noexcept
    {
        return m_vertex_spirv_words;
    }
    std::uint32_t fragmentSpirvWords() const noexcept
    {
        return m_fragment_spirv_words;
    }

    /// The staged uniform bytes (std140, sized by the layout table).
    const std::vector<std::byte>& uniformBytes() const noexcept
    {
        return m_uniform_bytes;
    }
    /// Whether any uniform was written since the last clearStaging().
    bool uniformStaged() const noexcept { return m_uniform_staged; }
    void clearStaging() noexcept { m_uniform_staged = false; }

    /// Sampler binding of a sampler uniform name on set 1; -1 when the name
    /// is not a sampler of this program.
    std::int32_t samplerBinding(const std::string& name) const;
    /// The program's sampler bindings (name -> binding on set 0), read from
    /// the layout table: the backend's descriptor set layout declares one
    /// CombinedImageSampler per entry, so the pipeline layout matches the
    /// SPIR-V's decorations.
    const std::map<std::string, std::int32_t>& samplers() const noexcept
    {
        return m_sampler_bindings;
    }

private:
    /// Writes value at the std140 offset of name (a no-op when the program
    /// has no such member, the same tolerance uniformLocation(-1) has).
    void writeUniform(const char* name, const void* data, std::uint32_t size);

    const std::uint32_t* m_vertex_spirv = nullptr;
    const std::uint32_t* m_fragment_spirv = nullptr;
    std::uint32_t m_vertex_spirv_words = 0;
    std::uint32_t m_fragment_spirv_words = 0;
    const ShaderBlockLayout::Member* m_members = nullptr;
    std::uint32_t m_member_count = 0;
    std::map<std::string, std::int32_t> m_sampler_bindings;
    std::vector<std::byte> m_uniform_bytes;
    bool m_uniform_staged = false;
};

}  // namespace grace::render::vulkan
