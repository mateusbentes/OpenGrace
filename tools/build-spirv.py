#!/usr/bin/env python3
"""Builds the SPIR-V for the Vulkan backend's shader library.

The library's GLSL 450 sources are extracted per shader, compiled to SPIR-V
by glslangValidator (the build-time prerequisite, decision 44), and the
generated header carries the per-shader byte arrays. The backend's
VkShaderProgram resolves through the same enum order as the library.

The broken pair (kBrokenVertexShader / kBrokenFragmentShader) is deliberately
invalid: its compilation failure is recorded in the generated header (an
empty array), so the backend's violation-count test observes the same
behaviour the OpenGL library documents.
"""
import re
import subprocess
import sys

LIBRARY = "src/render/vulkan/vulkan_shader_library.hpp"
GENERATED = "vulkan_spirv.hpp"

def main():
    if len(sys.argv) != 4:
        print("usage: build-spirv.py <source_dir> <generated_dir>"
              " <glslangValidator>",
              file=sys.stderr)
        return 2
    source_dir, generated_dir, glslang = sys.argv[1], sys.argv[2], sys.argv[3]
    library_text = open(source_dir + "/" + LIBRARY).read()
    shaders = re.findall(r'constexpr const char\* (\w+) = R"\((.*?)\n\)"',
                         library_text, re.S)
    out = ["// The Vulkan backend's compiled SPIR-V library. Generated by",
           "// tools/build-spirv.py from the GLSL 450 sources in",
           "// vulkan_shader_library.hpp (decision 44: glslangValidator is",
           "// the build-time prerequisite).",
           "#pragma once",
           "",
           "#include <cstdint>",
           "",
           "namespace grace::render::vulkan {",
           ""]
    compiled = 0
    for name, body in shaders:
        stage = "vert" if "VertexShader" in name else "frag"
        if name.endswith("VertexShader"):
            stage = "vert"
        elif name.endswith("FragmentShader"):
            stage = "frag"
        else:
            raise RuntimeError("unknown shader stage: " + name)
        stage_name = name + "." + stage
        stage_file = generated_dir + "/" + stage_name
        with open(stage_file, "w") as f:
            f.write(body + "\n")
        spv_file = generated_dir + "/" + name + ".spv"
        # The validator runs inside the generated directory so its error
        # messages carry only the file's base name: the recorded logs stay
        # stable across machines (no absolute paths in the header).
        result = subprocess.run([glslang, "-V", stage_name,
                                 "-o", name + ".spv"],
                                capture_output=True, text=True,
                                cwd=generated_dir)
        if result.returncode != 0:
            # The broken pair is expected to fail; the array is empty and
            # the backend's violation-count test observes the same failure
            # the OpenGL library documents.
            # GCC rejects a zero-size array, so the sentinel is one word
            # (the SPIR-V magic number is never the module's content: the
            # wrapper's word count is 0, and a zero word count is the
            # documented "compile failed" signal). The validator's log
            # text travels with the array so the backend's failure message
            # carries the real info log, the same wording the OpenGL
            # backend documents.
            log = (result.stderr or result.stdout or
                   "glslangValidator failed with no output").strip()
            log = log.replace("\\", "\\\\").replace('"', '\\"')
            log = log.replace("\n", "\\n")
            out.append("constexpr std::uint32_t %sSpirv[] = {0u};"
                       % name)
            out.append("constexpr std::uint32_t %sSpirvWords = 0;" % name)
            out.append('constexpr const char* %sLog = "%s";'
                       % (name, log))
            print("shader %s failed to compile (expected for the broken pair)"
                  % name, file=sys.stderr)
            continue
        spirv = open(spv_file, "rb").read()
        words = []
        for i in range(0, len(spirv), 4):
            words.append(int.from_bytes(spirv[i:i + 4], "little"))
        out.append("constexpr std::uint32_t %sSpirv[] = {" % name)
        for i in range(0, len(words), 4):
            chunk = words[i:i + 4]
            line = "    " + ", ".join("0x%08Xu" % w for w in chunk)
            if i + 4 < len(words):
                line += ","
            out.append(line)
        out.append("};")
        out.append("constexpr std::uint32_t %sSpirvWords = %d;"
                   % (name, len(words)))
        out.append("")
        compiled += 1
    out.append("}  // namespace grace::render::vulkan")
    with open(generated_dir + "/" + GENERATED, "w") as f:
        f.write("\n".join(out) + "\n")
    print("compiled %d of %d shaders to SPIR-V" % (compiled, len(shaders)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
